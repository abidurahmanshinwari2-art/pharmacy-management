export type MessageKey = keyof typeof dict.en;

type I18nValue = {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: MessageKey) => string;
  dir: "ltr" | "rtl";
};

const I18nContext = createContext<I18nValue | null>(null);

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const saved = localStorage.getItem("pharmacy_lang");
    return saved === "ps" || saved === "dari" || saved === "en" ? saved : "en";
  });

  function setLang(next: Lang) {
    setLangState(next);
    localStorage.setItem("pharmacy_lang", next);
  }

  const dir: "ltr" | "rtl" = "ltr";

  useEffect(() => {
    document.documentElement.lang = lang === "dari" ? "fa-AF" : lang;
    document.documentElement.dir = "ltr";
    document.title = dict[lang].shopName;
  }, [lang]);

  const value = useMemo<I18nValue>(
    () => ({
      lang,
      setLang,
      dir,
      t: (key) => dict[lang][key] || dict.en[key],
    }),
    [lang, dir]
  );

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("LanguageProvider missing");
  return ctx;
}

export function LanguageSwitch() {
  const { lang, setLang, t } = useI18n();
  const options: { id: Lang; label: string }[] = [
    { id: "en", label: t("english") },
    { id: "ps", label: t("pashto") },
    { id: "dari", label: t("dari") },
  ];
  return (
    <div>
      <div className="soft-label mb-1">{t("language")}</div>
      <div className="flex rounded-xl bg-white overflow-hidden border" style={{ borderColor: "var(--line)" }}>
        {options.map((option) => (
          <button
            key={option.id}
            type="button"
            className={`px-3 py-1.5 text-xs font-bold ${lang === option.id ? "text-white" : ""}`}
            style={lang === option.id ? { background: "var(--copper)", color: "#fff" } : { color: "var(--copper-deep)" }}
            onClick={() => setLang(option.id)}
          >
            {option.label}
          </button>
        ))}
      </div>
    </div>
  );
}
